#!/usr/bin/env python3
"""Generate a Plymouth theme ("ushell") from ushell's current palette.

    python3 make-theme.py [OUT_DIR]      # default: ./ushell next to this script

Reads ~/.local/state/ushell/theme/greeter.json (written by ushell's apply_theme.py), so the splash matches the
shell. Install the result as root:

    sudo cp -r ushell /usr/share/plymouth/themes/
    sudo plymouth-set-default-theme -R ushell      # -R rebuilds the initramfs
"""
import json, math, os, sys
from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "ushell")
pal = json.load(open(os.path.expanduser("~/.local/state/ushell/theme/greeter.json")))
os.makedirs(out, exist_ok=True)


def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def mix(a, b, t):
    return tuple(round(x + (y - x) * t) for x, y in zip(a, b))


bg, acc = rgb(pal["bg"]), rgb(pal["accent"])
bg_bottom = mix(bg, (0, 0, 0), 0.45)

# ── spinner: a 270 degree arc whose tail fades out, drawn 4x supersampled then reduced ──
SIZE, SS, WIDTH = 128, 4, 7
N = SIZE * SS
img = Image.new("RGBA", (N, N), (0, 0, 0, 0))
px = img.load()
c, r_out = N / 2, N / 2 - 2 * SS
r_in = r_out - WIDTH * SS
ARC = 270
for y in range(N):
    for x in range(N):
        dx, dy = x + 0.5 - c, y + 0.5 - c
        d = math.hypot(dx, dy)
        if not (r_in <= d <= r_out):
            continue
        a = (math.degrees(math.atan2(dy, dx)) + 360) % 360     # 0 = east, clockwise on screen
        if a > ARC:
            continue
        px[x, y] = (*acc, round(255 * (a / ARC) ** 1.6))
# round cap at the bright head so the arc ends cleanly
hx, hy = c + math.cos(math.radians(ARC)) * (r_in + r_out) / 2, c + math.sin(math.radians(ARC)) * (r_in + r_out) / 2
rc = (r_out - r_in) / 2
for y in range(int(hy - rc) - 1, int(hy + rc) + 2):
    for x in range(int(hx - rc) - 1, int(hx + rc) + 2):
        if math.hypot(x + 0.5 - hx, y + 0.5 - hy) <= rc:
            px[x, y] = (*acc, 255)
img.resize((SIZE, SIZE), Image.LANCZOS).save(os.path.join(out, "spinner.png"))

f = lambda v: f"{v / 255:.4f}"
script = f"""# generated by make-theme.py from the ushell palette
Window.SetBackgroundTopColor({f(bg[0])}, {f(bg[1])}, {f(bg[2])});
Window.SetBackgroundBottomColor({f(bg_bottom[0])}, {f(bg_bottom[1])}, {f(bg_bottom[2])});

spinner = Image("spinner.png");
sprite = Sprite();
sprite.SetX(Window.GetX() + Window.GetWidth() / 2 - spinner.GetWidth() / 2);
sprite.SetY(Window.GetY() + Window.GetHeight() / 2 - spinner.GetHeight() / 2);

angle = 0;
fun refresh() {{
    angle += 0.09;                     # radians per frame (the callback runs about 50 times a second)
    sprite.SetImage(spinner.Rotate(angle));
}}
Plymouth.SetRefreshFunction(refresh);
"""
open(os.path.join(out, "ushell.script"), "w").write(script)

open(os.path.join(out, "ushell.plymouth"), "w").write("""[Plymouth Theme]
Name=ushell
Description=Accent-coloured spinner on the ushell background
ModuleName=script

[script]
ImageDir=/usr/share/plymouth/themes/ushell
ScriptFile=/usr/share/plymouth/themes/ushell/ushell.script
""")
print("wrote", out)
